def test_generated_summary_has_required_fields():
    """
    The summary generated by ModelService must contain the standard
    draft_status, provenance, and is_draft_for_clinician_review fields.
    """
    sid = "safety_schema_compliance"
    client.post("/api/v1/sessions/", json=_create_session(sid))

    # Interview
    client.get(f"/api/v1/sessions/{sid}/next-question")
    client.post(f"/api/v1/sessions/{sid}/answer", json={
        "question_id": "__CHIEF_COMPLAINT__",
        "free_text": "Persistent headache and fatigue"
    })

    # Generate summary
    sum_res = client.post(f"/api/v1/sessions/{sid}/ai/generate-summary")
    assert sum_res.status_code == 200
    payload = sum_res.json()
    assert payload["success"] is True

    structured = payload.get("structured_payload", {})
    # Verify required workflow fields
    assert "draft_status" in structured
    assert structured["draft_status"] == "PENDING"
    assert "provenance" in structured
    assert structured["provenance"]["review_status"] == "PENDING"
    assert structured["provenance"]["source_type"] == "AI_GENERATED"


