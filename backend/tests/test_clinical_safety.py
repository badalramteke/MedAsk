# 1. Non-Diagnostic Safety Gate
# ============================================================================

def test_safety_gate_rejects_autonomous_diagnosis():
    """
    The ModelService safety gate must detect and reject AI output that
    contains autonomous diagnostic assertions (per PRD Section 11.4).
    """
    ms = ModelService()

    # Simulate a dangerous model response with prohibited diagnostic language
    dangerous_response = ModelTaskResponse(
        success=True,
        capability=ModelCapability.SUMMARY_SYNTHESIS,
        provider_used="test",
        raw_response="Based on the symptoms, you have been diagnosed with acute myocardial infarction. You must take this medication immediately.",
        structured_payload={"chief_complaint": "chest pain"},
        confidence_score=0.95
    )

    is_safe, violation = ms._validate_safety(dangerous_response)
    assert is_safe is False, f"Safety gate should have rejected this output but didn't. Violation: {violation}"
    assert len(violation) > 0


def test_safety_gate_accepts_observational_summary():
    """
    The safety gate must allow proper observational clinical summaries that
    describe findings without making autonomous diagnoses.
    """
    ms = ModelService()

    safe_response = ModelTaskResponse(
        success=True,
        capability=ModelCapability.SUMMARY_SYNTHESIS,
        provider_used="test",
        raw_response="Patient reports chest pain for 2 hours. Pain is substernal, crushing in character, radiating to left arm. Onset was sudden. This presentation suggests possible cardiac etiology requiring urgent evaluation.",
        structured_payload={"chief_complaint": "chest pain"},
        confidence_score=0.90
    )

    is_safe, violation = ms._validate_safety(safe_response)
    assert is_safe is True, f"Safety gate incorrectly rejected safe output: {violation}"


def test_all_prohibited_patterns_compiled_correctly():
    """Verify all prohibited diagnostic patterns are valid regex expressions."""
    for pattern in PROHIBITED_DIAGNOSTIC_PATTERNS:
        try:
            re.compile(pattern)
        except re.error as e:
            pytest.fail(f"Invalid regex pattern in safety rules: '{pattern}' - {e}")


